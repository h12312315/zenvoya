function render() {
  document.body.dataset.page = state.page;
  document.querySelectorAll('.nav-item').forEach(n => {
    const on = n.dataset.page === state.page;
    n.classList.toggle('active', on);
    if (on) n.setAttribute('aria-current', 'page'); else n.removeAttribute('aria-current');
  });
  $('#title').textContent = TITLES[state.page];
  $('#cartBadge').textContent = state.cart.length;
  $('#cartBadge').style.display = state.cart.length ? '' : 'none';
  const page = $('#page');
  if (page.dataset.page !== state.page) {
    destroyMaps();
    page.dataset.page = state.page;
    page.innerHTML = PAGES[state.page].shell();
    if (PAGES[state.page].mount) PAGES[state.page].mount();
  }
  if (PAGES[state.page].render) PAGES[state.page].render();
  renderCart();
  renderAttach('home');
  renderAttach('chat');
}

