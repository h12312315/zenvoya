function mountHome() {
  if (typeof maplibregl === 'undefined') return;
  homeMap = new maplibregl.Map({ container: 'homeMap', style: MAP_STYLE, center: [40, 36], zoom: 1.25, attributionControl: { compact: true } });
  const seen = new Set();
  allTrips().forEach(t => {
    if (seen.has(t.city.id)) return; seen.add(t.city.id);
    const el = document.createElement('button');
    el.className = 'home-pin'; el.title = t.city.name; el.style.backgroundImage = `url('${t.city.img}')`;
    el.dataset.act = 'open-trip'; el.dataset.city = t.city.id; el.dataset.chat = t.chat.id;
    const b = new maplibregl.LngLatBounds(); t.city.places.forEach(p => b.extend(p.ll));
    new maplibregl.Marker({ element: el }).setLngLat(b.getCenter()).addTo(homeMap);
  });
}

