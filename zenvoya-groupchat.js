/* ───────── Conversation logic ───────── */
function detect(text) {
  const dest = DESTINATIONS.find(([re]) => re.test(text));
  if (/flight|fly\b|airfare/i.test(text)) return { type: 'flights', dest: dest ? dest[1][0] : 'rome' };
  if (/\bstay|hotel|where to sleep/i.test(text)) return { type: 'hotels', dest: dest ? dest[1][0] : 'tokyo' };
  if (dest) return { type: 'trips', cities: dest[1], label: dest[2] };
  if (/trip|travel|vacation|holiday|explore|visit|getaway|ideas|somewhere|things to do/i.test(text)) return { type: 'trips', cities: ['tokyo', 'kyoto'], label: 'Japan' };
  return { type: 'chat' };
}

