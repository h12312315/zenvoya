  const text = `<div class="msg from-zoya">${group ? zoyaSVG() : ''}${m.typing ? '<span class="typing" aria-label="Zoya is typing"><i></i><i></i><i></i></span>' : `<span>${esc(m.text)}</span>`}</div>`;
