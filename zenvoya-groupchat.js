function mountTripMap(p) {
  if (typeof maplibregl === 'undefined') return;
  const city = CITIES[p.cityId];
  const b = new maplibregl.LngLatBounds();
  city.places.forEach(pl => b.extend(pl.ll));
  tripMap = new maplibregl.Map({
    container: 'tpMap', style: MAP_STYLE, bounds: b, attributionControl: { compact: true },
    fitBoundsOptions: { padding: { top: 76, bottom: SHEET.trip.peek + 40, left: 48, right: 48 }, maxZoom: 13.5 },
  });
  city.places.forEach(pl => {
    const el = document.createElement('button');
    el.className = 'pin'; el.textContent = pl.emoji; el.title = pl.name; el.setAttribute('aria-label', pl.name);
    el.dataset.act = 'open-loc'; el.dataset.place = pl.id;
    tripMarkers[pl.id] = el;
    new maplibregl.Marker({ element: el }).setLngLat(pl.ll).addTo(tripMap);
  });
}

