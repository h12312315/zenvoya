function peopleDone() {
  const p = state.pop, chat = activeChat(), sel = FRIENDS.map(f => f.id).filter(id => p.sel.has(id));
  let joined = [];
  if (p.type === 'chat-people') {
    const added = sel.filter(id => !chat.members.includes(id)), removed = chat.members.filter(id => !sel.includes(id));
    chat.members = sel;
    if (added.length) chat.messages.push({ system: true, text: `You added ${names(added)} to this chat` });
    if (removed.length) chat.messages.push({ system: true, text: `You removed ${names(removed)} from this chat` });
    joined = added;
  } else {
    const trip = tripOf(chat, chat.panel.cityId), city = CITIES[trip.cityId];
    const added = sel.filter(id => !trip.members.includes(id)), removed = trip.members.filter(id => !sel.includes(id));
    const wasSolo = !chat.members.length;
    joined = sel.filter(id => !chat.members.includes(id));
    trip.members = sel;
    chat.members.push(...joined);
    if (added.length) chat.messages.push({ system: true, text: `You added ${names(added)} to ${city.name} ${trip.days} days` + (joined.length ? (wasSolo ? '. This is now a group chat.' : '. They joined this chat too.') : '') });
    if (removed.length) chat.messages.push({ system: true, text: `You removed ${names(removed)} from ${city.name} ${trip.days} days` });
  }
  closePop();
  render();
  if (joined.length) setTimeout(() => { chat.messages.push({ from: joined[0], text: 'Thanks for adding me! This looks great 😍' }); refresh(chat); }, 1200);
}

